// vbaLibrary() tests (vba-core): the built-in functions called directly, no parser needed.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { vbaLibrary } from '../src/lab/vba/builtins.ts'
import { toStr } from '../src/lab/vba/coerce.ts'
import { EMPTY, NULL_VAL, VbaError, bool, dbl, int, lng, str, type RunCtx, type Val } from '../src/lab/vba/runtime.ts'
import { fakeHost } from './vbaCoreHarness.ts'

const lib = vbaLibrary()
const fake = fakeHost(['typed', null], [6])
const ctx: RunCtx = { host: fake.host, compareText: false, err: { number: 0, description: '', source: '' } }

function call(name: string, ...args: (Val | string | number | boolean)[]): Val {
  const g = lib.get(name.toLowerCase())
  if (!g || g.kind !== 'fn') throw new Error(`no function ${name}`)
  const vals = args.map(a => (typeof a === 'string' ? str(a) : typeof a === 'number' ? (Number.isInteger(a) ? int(a) : dbl(a)) : typeof a === 'boolean' ? bool(a) : a))
  return g.fn(ctx, vals, {})
}
const s = (name: string, ...args: (Val | string | number | boolean)[]): string => toStr(call(name, ...args))
const errNo = (fn: () => unknown): number => {
  try { fn() } catch (e) { if (e instanceof VbaError) return e.number; throw e }
  return 0
}
const D = (y: number, m: number, d: number): Val => ({ t: 'date', v: (Date.UTC(y, m - 1, d) - Date.UTC(1899, 11, 30)) / 86400000 })

test('lib: Len, Left, Right, Mid, Trim, case', () => {
  assert.deepEqual(call('Len', 'hello'), lng(5))
  assert.deepEqual(call('Len', NULL_VAL), NULL_VAL)
  assert.equal(s('Left', 'hello', 2), 'he')
  assert.equal(s('Right', 'hello', 3), 'llo')
  assert.equal(s('Right', 'hello', 0), '')
  assert.equal(s('Mid', 'hello', 2, 3), 'ell')
  assert.equal(s('Mid', 'hello', 4), 'lo')
  assert.equal(s('Mid', 'hello', 9), '')
  assert.equal(errNo(() => call('Mid', 'hello', 0)), 5)
  assert.equal(errNo(() => call('Left', 'hello', -1)), 5)
  assert.equal(s('Trim', '  a b  '), 'a b')
  assert.equal(s('LTrim', '  a '), 'a ')
  assert.equal(s('RTrim', ' a  '), ' a')
  assert.equal(s('UCase', 'is602'), 'IS602')
  assert.equal(s('LCase', 'ABC'), 'abc')
  assert.equal(s('Left$', 'abc', 1), 'a')
  assert.equal(errNo(() => call('Left$', NULL_VAL, 1)), 94)
})

