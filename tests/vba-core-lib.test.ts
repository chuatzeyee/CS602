  assert.deepEqual(k('vbcrlf'), str('\r\n'))
  assert.deepEqual(k('vbyes'), lng(6))
  assert.deepEqual(k('vbred'), lng(255))
  assert.deepEqual(k('vbtextcompare'), lng(1))
  assert.deepEqual(k('vbsaturday'), lng(7))
