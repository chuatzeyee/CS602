test('lib: Array, Split, Join, LBound, UBound, Filter', () => {
  const a = call('Array', 1, 'b', true)
  assert.equal(a.t, 'arr')
  assert.deepEqual(call('LBound', a), lng(0))
  assert.deepEqual(call('UBound', a), lng(2))
  const parts = call('Split', 'a,b,,c', ',')
  assert.deepEqual(call('UBound', parts), lng(3))
  assert.equal(s('Join', parts, '|'), 'a|b||c')
  assert.equal(s('Join', call('Split', 'x y z')), 'x y z')
  assert.deepEqual(call('UBound', call('Split', 'a,b,c', ',', 2)), lng(1))
  assert.deepEqual(call('UBound', call('Split', '')), lng(-1))
  assert.equal(s('Join', call('Filter', call('Split', 'apple,banana,cherry', ','), 'an')), 'banana')
  assert.equal(errNo(() => call('UBound', 5)), 13)
  assert.equal(errNo(() => call('UBound', a, 2)), 9)
})

